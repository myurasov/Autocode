/*
 * Builds the autocode binary (server and CLI in one) with the plugin bundle and
 * the web UI inside.
 *   bun cli/build.ts
 *     the host's own platform -> dist/autocode
 *   AUTOCODE_TARGETS=all bun cli/build.ts
 *     adds linux-arm64, linux-x64, darwin-arm64 -> dist/autocode-<target>
 *   bun cli/build.ts --generate
 *     only writes src/generated/ (needed before type checks)
 * AUTOCODE_BUILD=<n> numbers the build (ci/dist.sh): its version is
 * "<release>-build<n>", else "<release>-dev".
 */
import { existsSync, readdirSync, statSync } from "node:fs"
import { mkdir, writeFile } from "node:fs/promises"
import { join, relative, resolve } from "node:path"
import { buildPlugin } from "../plugin/build.ts"

const root = resolve(import.meta.dir, "..")
const generated = resolve(import.meta.dir, "src/generated")
const webDist = resolve(root, "web/dist/web/browser")
const all = ["linux-arm64", "linux-x64", "darwin-arm64"] as const
const bunTarget: Record<string, string> = {
  "linux-arm64": "bun-linux-arm64",
  "linux-x64": "bun-linux-x64-baseline",
  "darwin-arm64": "bun-darwin-arm64",
}

function files(dir: string): string[] {
  const out: string[] = []
  for (const name of readdirSync(dir)) {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) out.push(...files(path))
    else out.push(path)
  }
  return out
}

// The plugin bundle as a string, and the web UI files as imports the compiler
// embeds ({ type: "file" }).
export async function generate(options: { build?: string } = {}) {
  const pluginFile = await buildPlugin(root, { build: options.build })
  await mkdir(generated, { recursive: true })
  await writeFile(
    resolve(generated, "plugin.ts"),
    "// @ts-nocheck\n// Generated by cli/build.ts.\n" +
      `export default ${JSON.stringify(await Bun.file(pluginFile).text())} ` +
      "as string\n",
  )
  const web = existsSync(webDist) ? files(webDist) : []
  const lines = [
    "// @ts-nocheck",
    "// Generated by cli/build.ts: the web UI files, embedded in " +
      "the binary.",
  ]
  web.forEach((file, i) => {
    lines.push(
      `import f${i} from ${JSON.stringify(relative(generated, file))} ` +
        `with { type: "file" }`,
    )
  })
  lines.push("export default {")
  web.forEach((file, i) => {
    lines.push(
      `  ${JSON.stringify(
        `/${relative(webDist, file).split("\\").join("/")}`,
      )}: f${i},`,
    )
  })
  lines.push("} as Record<string, string>", "")
  await writeFile(resolve(generated, "web.ts"), lines.join("\n"))
}

export async function compileCli(
  outfile: string,
  options: { target?: string; build?: string } = {},
) {
  const { target, build } = options
  const entry = resolve(import.meta.dir, "src/main.ts")
  const args = ["build", "--compile", entry, "--outfile", outfile]
  if (target) args.push(`--target=${bunTarget[target] ?? target}`)
  if (build) args.push("--define", `AUTOCODE_BUILD=${JSON.stringify(build)}`)
  const proc = Bun.spawn(["bun", ...args], {
    cwd: root,
    stdout: "inherit",
    stderr: "inherit",
  })
  if ((await proc.exited) !== 0)
    throw new Error(`compile failed for ${target ?? "host"}`)
}

if (import.meta.main) {
  const build = process.env.AUTOCODE_BUILD || undefined
  if (build && !/^\d+$/.test(build))
    throw new Error(`AUTOCODE_BUILD is not a number: ${build}`)
  await generate({ build })
  if (!process.argv.includes("--generate")) {
    const wanted =
      process.env.AUTOCODE_TARGETS === "all"
        ? [...all]
        : (process.env.AUTOCODE_TARGETS?.split(",").filter(Boolean) ?? [])
    await compileCli(resolve(root, "dist/autocode"), { build })
    for (const target of wanted)
      await compileCli(resolve(root, `dist/autocode-${target}`), {
        target,
        build,
      })
  }
}
